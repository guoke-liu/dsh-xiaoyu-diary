/**
 * day.js（日记日）的测试。
 *
 * 这个模块解决的是「一条日记该算哪一天」——凌晨 3 点前记的算前一天。
 * 起因是真实数据里看到的一段：私聊 11-03 最后一句是 22:32「那我先睡一会儿」，
 * 11-04 第一句是 01:30「宝宝」，同一段会话被 00:00 切成两个文件。
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'

import { 日记日, 前推天数, 规范小时数, 默认时区, 默认日记日起点小时 } from '../lib/day.js'

test('日记日：凌晨 3 点前算前一天，3 点后算当天', () => {
  const 时区 = 'Asia/Shanghai'
  assert.equal(日记日(new Date('2026-11-04T01:30:00+08:00'), { 时区 }), '2026-11-03', '凌晨 1:30 应归前一天')
  assert.equal(日记日(new Date('2026-11-04T02:59:00+08:00'), { 时区 }), '2026-11-03', '凌晨 2:59 仍算前一天')
  assert.equal(日记日(new Date('2026-11-04T03:00:00+08:00'), { 时区 }), '2026-11-04', '3 点整算当天')
  assert.equal(日记日(new Date('2026-11-04T09:00:00+08:00'), { 时区 }), '2026-11-04', '上午算当天')
})

test('日记日：按指定时区算，不是按服务器本机时区', () => {
  // 云端机器是 UTC。同一时刻，UTC 下是 17:30 算当天，上海下是次日 01:30 算前一天。
  const 时刻 = new Date('2026-11-03T17:30:00Z')
  assert.equal(日记日(时刻, { 时区: 'UTC' }), '2026-11-03')
  assert.equal(日记日(时刻, { 时区: 'Asia/Shanghai' }), '2026-11-03', '上海时间 01:30 应算 11-03')
  // 再来一个能分出高下的：UTC 20:00 = 上海次日 04:00
  const 另一刻 = new Date('2026-11-03T20:00:00Z')
  assert.equal(日记日(另一刻, { 时区: 'UTC' }), '2026-11-03')
  assert.equal(日记日(另一刻, { 时区: 'Asia/Shanghai' }), '2026-11-04', '上海 04:00 已过起点，算当天')
})

test('日记日：起点小时可调，非法值一律夹回 0..23', () => {
  assert.equal(规范小时数(0), 0)
  assert.equal(规范小时数(3), 3)
  assert.equal(规范小时数(23), 23)
  assert.equal(规范小时数(99), 23, '超范围夹回 23')
  assert.equal(规范小时数(-5), 0, '负数夹回 0')
  assert.equal(规范小时数('abc'), 默认日记日起点小时, '非数字用默认值')
  assert.equal(规范小时数(null), 默认日记日起点小时)
})

test('日记日：时区名写错不抛，退回本机时区照常给日期', () => {
  const 坏 = 日记日(new Date('2026-11-04T12:00:00Z'), { 时区: '不是个时区/瞎写的' })
  assert.match(坏, /^\d{4}-\d{2}-\d{2}$/, `坏时区也要给得出日期，实际：${坏}`)
  assert.ok(!坏.includes('NaN'), '绝不能给出 NaN-NaN-NaN')
})

test('日记日：日期算术跨月/跨年/闰年都对', () => {
  assert.equal(前推天数('2026-11-01', 1), '2026-10-31', '跨月')
  assert.equal(前推天数('2026-01-01', 1), '2025-12-31', '跨年')
  assert.equal(前推天数('2024-03-01', 1), '2024-02-29', '闰年 2 月 29 日')
  assert.equal(前推天数('2025-03-01', 1), '2025-02-28', '平年 2 月 28 日')
  assert.equal(前推天数('2026-11-04', -1), '2026-11-05', '负数往后推')
})

test('默认值：时区是 Asia/Shanghai，起点 3 点', () => {
  assert.equal(默认时区, 'Asia/Shanghai')
  assert.equal(默认日记日起点小时, 3)
})
