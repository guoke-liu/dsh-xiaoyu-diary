// ============================================================================
// extract.js —— 从记忆仓库当天的聊天记录里挑出「不能忘的事」
//
// 【这个模块负责什么】
//   把记忆仓库当天的聊天记录（已解析成行数组）按五类可解释的规则筛出候选，
//   交给模型或人在 UI 上做最终取舍。本模块**只筛不写**：判断不了哪条真重要，
//   也不把候选直接写进日记。
//
// 【为什么这样设计】
//   设计原则：这里是初筛，不是终审。
//   本模块**不做语义理解** —— 它判断不了「这句话对他重不重要」。
//   它只用可解释的规则筛出「可能值得记」的候选，交给模型做最终取舍。
//
//   为什么这样分工：
//   · 聊天记录一天几千行，全塞给模型既贵又吵；
//   · 规则筛完通常剩几十行，模型扫一眼就能挑；
//   · 规则是可读的，筛错了能查出来是哪条规则的问题。
//
//   五类信号（各自独立打分，可叠加）：
//   1. 承诺/计划     「明天」「下周」「我答应」「记得」「约好」
//   2. 决定/结论     「决定」「就定」「选了」「确认了」「改成」
//   3. 重要信息      「密码」「地址」「电话」「账号」「多少钱」「deadline」
//   4. 情绪强度      「气死」「难受」「开心」「烦」「难过」「太棒了」
//   5. 问题/未解决   「怎么办」「没搞定」「失败」「报错」「卡住」
//
// 【对外导出】
//   · 解析聊天(raw) —— 解析一天的聊天文件文本 → 行数组（非格式行直接丢弃）
//   · 给行打分(行) —— 给一行打分，命中的信号类别全部收集起来
//   · 挑候选(行们, {上限, 最短分}) —— 从一整天的聊天里挑候选（去重 + 打分 + 排序）
//   · 渲染候选(候选, {日期, 总行数}) —— 把候选渲染成给模型读的文本
// ============================================================================

import { 来源标签 } from './source.js'

/** 聊天行的解析器，与记忆仓库 chatlog 的格式一致：[HH:MM:SS] 昵称(pid): 内容 */
const 行格式 = /^\[(\d{2}):(\d{2}):(\d{2})\]\s*([^(]*)\(([^)]+)\):\s*(.*)$/

/**
 * 信号词表。
 *
 * 每条都是「可能意味着这件事值得记」的线索，不是「必须记」的判据。
 *
 * ⚠️ 加词前先想清楚误报率。用云端真实数据（2026-11-03，222 行群聊）实测过一轮：
 *    「安排」「换成」「改成」「一会儿」这类词在画图/闲聊里极多，
 *    「安排」4 次、「换成」4 次、「改成」3 次全是画图指令造成的误报 ——
 *    它们已从词表移除。宁可漏一点，也不要每天给用户塞一堆垃圾候选。
 *
 * 收词原则：只收「脱离具体语境也意味着有承诺/有决定」的词。
 * 泛动词（安排、改成、换成）不算 —— 它们在任何对话里都高频。
 */
const 信号们 = [
  {
    // 只看真正指向未来的时间承诺。
    //
    // ⚠️ 实测教训（2026-11-02 真实私聊 159 行）：
    //   · 单独一个「记得」命中 5 条，其中「你还记得…吗」是**提问**、
    //     「记得记日记」是自我提醒，都不是对别人的承诺 —— 已收紧成「我记得 / 记得要 / 记得去」。
    //   · 「一会儿」「稍后」「待会」太随口，不收。
    //   · 「安排」「改成」「换成」是画图/闲聊的高频泛动词，早在上一轮就移除了。
    // 收词标准：去掉这些词之后，这句话就不成立了，才算强承诺。
    类别: '承诺计划',
    权重: 3,
    词们: ['明天', '后天', '下周', '下个月', '周末', '约定', '约好', '答应', '我保证',
      '我记得', '记得要', '记得去', '别忘了', '改天', '计划', '要去做', '打算'],
  },
  {
    // 只收「做出了选择/定下了规则」的词；泛动词（改成、换成）不收
    类别: '决定结论',
    权重: 3,
    词们: ['决定', '就定', '定了', '确认了', '以后就', '从今', '规定', '原则'],
  },
  {
    类别: '重要信息',
    权重: 4,
    词们: ['密码', '账号', '地址', '电话', '手机号', '身份证', '号码', '金额', '多少钱',
      '付款', '转账', '截止', 'deadline', '到期', '合同', '签约', '订单', '发货', '收货'],
  },
  {
    // 只留「情绪强度大到值得记下来」的词。
    //
    // ⚠️ 用 2026-11-03 的真实私聊实测过：「开心」「高兴」是日常寒暄里的高频词，
    //    一天能占满 4 个候选名额（「你玩的开心就好」「一高兴就自己走了」…），
    //    那些都不是"不能忘的事"，纯粹把名额挤掉。已移除。
    //    同理「烦」「不行」「太棒」也太泛，不收。
    //
    // 收词标准：这个词出现，通常意味着**发生了某件事**（争吵、崩溃、离别、感动），
    // 而不只是心情不错。日常报平安式的"开心"不算。
    类别: '情绪强度',
    权重: 2,
    词们: ['气死', '难受', '难过', '烦死', '崩溃', '委屈', '生气', '失望',
      '害怕', '焦虑', '感动', '心疼', '舍不得'],
  },
  {
    类别: '未解决',
    权重: 2,
    词们: ['怎么办', '没搞定', '没成功', '失败', '报错', '错误', '卡住', '卡在',
      '有问题', 'bug', '崩了', '挂了', '搞不定'],
  },
]

/** 太短的行不算内容（「嗯」「好的」「哈哈」这种没有信息量）。 */
const 最短字数 = 4

/**
 * 解析一天的聊天文件文本 → 行数组。
 * 不是这个格式的行直接丢弃，不要试图猜。
 */
export function 解析聊天 (raw) {
  const out = []
  for (const line of String(raw || '').split(/\r?\n/)) {
    const t = line.trim()
    if (!t) continue
    const m = t.match(行格式)
    if (!m) continue
    out.push({
      时间: `${m[1]}:${m[2]}:${m[3]}`,
      昵称: m[4].trim(),
      pid: m[5],
      内容: m[6],
      原文: t,
    })
  }
  return out
}

/**
 * 给一行打分。命中的信号类别全部收集起来，便于向模型解释「为什么挑它」。
 *
 * 【关键约束：没有信号就没有分】
 * 长度加分只是**修正项**，不能独立把一句话送进候选。
 * 曾经的写法是「先无条件加长度分」，于是一条没有任何信号词的长句能拿到 2 分，
 * 正好够到候选门槛（最短分=2）—— 实测 2026-11-03 的真实数据里，
 * 有 2 条候选是这么混进来的（一条是搬家公告，一条是 URL）。
 *
 * 现在的规则：**必须先命中至少一类信号，长度分才生效**。
 * 这样「长」只用来在同有信号的句子里拉开差距，不能自己造出候选。
 *
 * @returns {{分: number, 命中: string[]}}
 */
export function 给行打分 (行) {
  const 文 = 行.内容
  if (文.length < 最短字数) return { 分: 0, 命中: [] }
  let 分 = 0
  const 命中 = []
  for (const sig of 信号们) {
    const hit = sig.词们.filter((w) => 文.includes(w))
    if (hit.length > 0) {
      分 += sig.权重
      命中.push(`${sig.类别}(${hit.slice(0, 3).join('/')})`)
    }
  }
  // 没命中任何信号：一律 0 分，长度再长也不加分
  if (命中.length === 0) return { 分: 0, 命中: [] }
  // 有信号的前提下，长句信息量更大：超过 60 字再补 1 分（收益递减）
  if (文.length >= 60) 分 += 1
  return { 分, 命中 }
}

/**
 * 从一整天的聊天里挑候选。
 *
 * 去重：同一个人连续说同样的话只留最后一条 —— 刷屏的不算重要的事。
 *
 * @param {Array} 行们 解析后的行
 * @param {{上限?:number, 最短分?:number}} [opts]
 * @returns {{候选: object[], 总行数: number, 有信号行数: number}}
 */
export function 挑候选 (行们, { 上限 = 80, 最短分 = 2 } = {}) {
  const 见过的 = new Set()
  const 打分后 = []
  for (const 行 of 行们) {
    const key = `${行.pid}|${行.内容}`
    if (见过的.has(key)) continue
    见过的.add(key)
    const r = 给行打分(行)
    if (r.分 < 最短分) continue
    // 带上 .来源（'private' / 'group:<群号>'）：候选按来源分开存，
    // 这一项跟着候选写进 candidates/<来源>/<date>.json，回头能对上是谁说的
    打分后.push({ ...行, 分: r.分, 命中: r.命中, 来源: 行.来源 || '' })
  }
  // 分高的先留；同分按时间先后，保持原顺序便于模型读上下文
  打分后.sort((a, b) => b.分 - a.分)
  const 选中 = 打分后.slice(0, 上限)
  选中.sort((a, b) => (a.时间 < b.时间 ? -1 : a.时间 > b.时间 ? 1 : 0))
  return { 候选: 选中, 总行数: 行们.length, 有信号行数: 打分后.length }
}

/**
 * 把候选渲染成一段给模型读的文本。
 *
 * 刻意带上「这条是被什么规则挑中的」：模型据此判断值不值得记，
 * 人回头看时也能知道当时的筛选依据。
 */
export function 渲染候选 (候选, { 日期, 总行数, 来源 } = {}) {
  const 来源字样 = 来源 ? `${来源标签(来源)} · ` : ''
  if (候选.length === 0) {
    return `【${日期 || '当天'}】${来源字样}从 ${总行数 || 0} 行聊天里没有筛出候选（可能当天没什么值得记的事）。`
  }
  const lines = [
    `【${日期 || '当天'}】${来源字样}共 ${总行数 || 0} 行聊天，按规则筛出 ${候选.length} 条候选。`,
    '规则只做初筛、不懂语义：请判断哪些是「真正不能忘的事」，其余丢弃。',
    '',
  ]
  for (const c of 候选) {
    lines.push(`[${c.时间}] ${c.昵称}: ${c.内容}`)
    lines.push(`    └ 初筛信号：${c.命中.join('；') || '无'}`)
    if (c.来源 && c.来源 !== 来源) lines.push(`    └ 来自：${来源标签(c.来源)}`)
  }
  return lines.join('\n')
}
